module ArbitraryPrecisionReport

using Chairmarks
using DoubleFloats
using GenericLinearAlgebra
using LinearAlgebra
using PlasmaBO
using Printf
using SpecialFunctions
using Statistics

const REPORT_BITS = 128
setprecision(BigFloat, 256)

vz = collect(range(-6, 6; length = 1201))
vx = collect(range(0, 6; length = 201))
fv = [abs(z) <= 1 ? exp(-x^2) : 0.0 for z in vz, x in vx]
alm = hermite_expansion(fv, vz, vx, 1.0, 1.0; Nz = 32, Nx = 0).alm

const N = 1
const J = 4
const SNJ = (2N + 1) * J
const SNJ1 = SNJ + 1
const ROWS = [SNJ + 1, SNJ + SNJ1 + 1, SNJ + 2SNJ1 + 1]
const COLS = (3SNJ1 + 1):(3SNJ1 + 3)

const TYPES = [
    ("Float64", Float64),
    ("Double64", Double64),
    ("BigFloat128", BigFloat),
]

function report_matrix(::Type{T}) where {T}
    p = HHSolverParam{T}(
        one(T), one(T), one(T), one(T), one(T), zero(T), zero(T), T.(alm),
    )
    return dispersion_matrix((p,), one(T), T(0.2), T(0.1), BOHH; N, J)
end

report_block(T) = report_matrix(T)[ROWS, COLS]

Bref = setprecision(256) do
    report_block(BigFloat)
end

function relative_error(::Type{T}) where {T}
    block = T === BigFloat ? setprecision(REPORT_BITS) do
        report_block(BigFloat)
    end : report_block(T)
    return setprecision(256) do
        norm(Complex{BigFloat}.(block) - Bref) / norm(Bref)
    end
end

function timed(f)
    f()
    r = @be $f() evals = 1 samples = 10 seconds = 10
    return (
        median_seconds = median(getproperty.(r.samples, :time)),
        allocations = median(Float64.(getproperty.(r.samples, :allocs))),
        bytes = median(Float64.(getproperty.(r.samples, :bytes))),
    )
end

solve_for(::Type{Float64}) = eigvals(report_matrix(Float64))
solve_for(::Type{Double64}) = eigvals(report_matrix(Double64))
solve_for(::Type{BigFloat}) = setprecision(REPORT_BITS) do
    eigvals(report_matrix(BigFloat))
end

asm_for(::Type{Float64}) = report_matrix(Float64)
asm_for(::Type{Double64}) = report_matrix(Double64)
asm_for(::Type{BigFloat}) = setprecision(REPORT_BITS) do
    report_matrix(BigFloat)
end

errors = [(label, Float64(relative_error(T))) for (label, T) in TYPES]
asm = [(label, timed(() -> asm_for(T))) for (label, T) in TYPES]
slv = [(label, timed(() -> solve_for(T))) for (label, T) in TYPES]

asm_base = asm[1][2].median_seconds
slv_base = slv[1][2].median_seconds

const OUT = joinpath(@__DIR__, "results.toml")

function bench_block(io, name, rows, base)
    println(io, "[$name]")
    for (label, r) in rows
        println(io, "[$name.$label]")
        println(io, "median_ms = ", round(1.0e3 * r.median_seconds; sigdigits = 4))
        println(io, "slowdown = ", round(r.median_seconds / base; sigdigits = 4))
        println(io, "allocs = ", Int(round(r.allocations)))
        println(io, "kib = ", round(r.bytes / 1024; sigdigits = 4))
        println(io)
    end
    return nothing
end

open(OUT, "w") do io
    println(io, "# Auto-generated by arbitrary_precision_report.jl. Do not edit.")
    println(io, "report_bits = ", REPORT_BITS)
    println(io, "reference_bits = 256")
    println(io)
    println(io, "[errors]")
    for (label, err) in errors
        println(io, "$label = \"", Printf.@sprintf("%.4e", err), "\"")
    end
    println(io)
    bench_block(io, "assembly", asm, asm_base)
    bench_block(io, "solve", slv, slv_base)
end

println("wrote ", OUT)

end
